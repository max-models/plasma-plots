def _mdx_text(text: str) -> str:
    """reST text for MDX: double backticks to single, and { and < escaped outside code spans."""
    parts = text.replace("``", "`").split("`")
    for i in range(0, len(parts), 2):
        parts[i] = parts[i].replace("{", "\\{").replace("<", "&lt;")
    return "`".join(parts)


def methods(cls):
    """Public methods and properties of a class, in source order."""
    members = [
        m
        for name, m in cls.members.items()
        if not name.startswith("_")
        and not m.is_alias
        and (m.is_function or "property" in m.labels)
    ]
    return sorted(members, key=lambda m: m.lineno or 0)


def render(package, slug) -> str:
    title, description, intro, classes = PAGES[slug]
    order = list(PAGES).index(slug) + 1
    lines = [
        "---",
        f'title: "{title}"',
        f'description: "{description}"',
        "sidebar:",
        f"  order: {order}",
        "---",
        "",
        "{/* Written by scripts/accessor_pages.py; edit that script, not this page. */}",
        "",
        "import { Autodoc } from 'starlight-pydocs/components';",
        "",
        intro,
        "",
        NOTE,
        "",
    ]
    for path, heading in classes:
        cls = package[path]
        lines += [f"## {heading}", ""]
        summary = cls.docstring.value.strip().splitlines()[0] if cls.docstring else ""
        if summary:
            lines += [_mdx_text(summary), ""]
        for method in methods(cls):
            lines += [
                f"### `{method.name}`",
                "",
                f'<Autodoc name="plasma_plots.{path}.{method.name}" package="plasma_plots" headingLevel={{3}} />',
                "",
            ]
    return "\n".join(lines).rstrip() + "\n"


def main():
    package = griffe.load(
        "plasma_plots", search_paths=[str(ROOT / "src")], docstring_parser="numpy"
    )
    stale = []
    for slug in PAGES:
        path = OUT / f"{slug}.mdx"
        text = render(package, slug)
        if "--check" in sys.argv:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print(
            "out of date (run python scripts/accessor_pages.py):\n" + "\n".join(stale)
        )
        sys.exit(1)


if __name__ == "__main__":
    main()
