"""Write the accessor pages of the API reference (docs/src/content/docs/reference/*.mdx).

Each page embeds one method per ``<Autodoc>`` block, in source order, under a heading of its own:
starlight-pydocs renders the method, and the heading gives Starlight's "On this page" panel an
entry for it (the panel only sees the page's own Markdown headings; the CSS in custom.css hides the
duplicate). The module pages under /api/plasma_plots/ are generated by starlight-pydocs itself.

Run from the repo root after adding, removing or reordering accessor methods:

    python scripts/accessor_pages.py            # write the pages
    python scripts/accessor_pages.py --check    # fail if they are out of date (tests/test_accessor_pages.py)
"""

